USE `family_genealogy`;

-- ------------------------------------------------------------
-- 建表
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `history_events` (
  `id`          INT UNSIGNED  NOT NULL AUTO_INCREMENT COMMENT '主键',
  `year`        INT           NOT NULL COMMENT '年份（负数表示公元前）',
  `title`       VARCHAR(100)  NOT NULL COMMENT '事件标题',
  `dynasty`     VARCHAR(50)   NOT NULL DEFAULT '' COMMENT '朝代',
  `description` VARCHAR(500)  NOT NULL DEFAULT '' COMMENT '事件描述（含与家族迁徙相关的背景）',
  `category`    VARCHAR(20)   NOT NULL DEFAULT 'politics' COMMENT '分类: politics-政治 war-战争 culture-文化 economy-经济 society-社会迁徙 science-科技',
  `region`      VARCHAR(200)  DEFAULT '' COMMENT '关联地域（逗号分隔，未来按家族籍贯精准匹配用，空=全国通用）',
  `keywords`    VARCHAR(200)  DEFAULT '' COMMENT '搜索关键词（逗号分隔，用于模糊匹配）',
  `sort_order`  INT           DEFAULT 0 COMMENT '同一年份的排序权重（越大越靠前）',
  `status`      TINYINT(1)    DEFAULT 1 COMMENT '状态 1-启用 0-禁用',
  `create_time` DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  INDEX `idx_year` (`year`),
  INDEX `idx_category` (`category`),
  INDEX `idx_year_category` (`year`, `category`),
  INDEX `idx_status` (`status`)
) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
  COLLATE=utf8mb4_unicode_ci
  COMMENT='同期历史事件表（时空地图模块，支持后台编辑的中国历史大事年表）';

